#!/usr/bin/env python3
"""Write paper/v2/numbers.tex: one LaTeX macro per number quoted in the paper,
read from the committed result files in results/.

    python -m v2.make_numbers
"""
import json

import numpy as np

import beam_parameters as bp

RES = "results"


def f(x, d=1):
    return f"{x:.{d}f}"


def sig(x, n=2):
    """Round to n significant figures for quoting reaches."""
    if x <= 0:
        return "0"
    p = int(np.floor(np.log10(abs(x))))
    v = round(x, n - 1 - p)
    return f"{v:.{max(n - 1 - p, 0)}f}"


def main():
    r = json.load(open(f"{RES}/v2_results.json"))
    tg = json.load(open(f"{RES}/truth_gates.json"))
    cl = json.load(open(f"{RES}/closure.json"))
    wz = json.load(open(f"{RES}/whizard_check.json"))
    m = {}
    m["Lumi"] = f(bp.INTEGRATED_LUMI_AB, 1)
    m["SigmaZH"] = f(bp.SIGMA_ZH_FB, 0)
    m["BES"] = f(bp.BEAM_ENERGY_SPREAD * 100, 3)
    m["LumRegX"] = f(bp.LUMINOUS_REGION_MM[0] * 1e3, 1)
    m["LumRegY"] = f(bp.LUMINOUS_REGION_MM[1] * 1e6, 0)
    m["LumRegZ"] = f(bp.LUMINOUS_REGION_MM[2], 2)
    y = r["yields"]
    for mode, tag in (("mumu", "MuMu"), ("ee", "EE"), ("qq", "QQ")):
        m[f"NGen{tag}"] = f(y[mode]["events_generated_at_lumi"], 0)
        m[f"NSel{tag}"] = f(y[mode]["events_selected_at_lumi"], 0)
        m[f"Eff{tag}"] = f(100 * y[mode]["cumulative_efficiency"]["vertex_quality"], 0)
        m[f"EffPre{tag}"] = f(100 * y[mode]["cumulative_efficiency"]["reco_ok"], 0)
        m[f"EffID{tag}"] = f(100 * y[mode]["cumulative_efficiency"]["pi_nu_id"], 0)
    m["NPerAbMuMu"] = f(y["mumu"]["events_per_ab_generated"], 1)
    m["NSelLL"] = f(y["mumu"]["events_selected_at_lumi"] + y["ee"]["events_selected_at_lumi"], 0)
    m["NSelVis"] = f(sum(y[k]["events_selected_at_lumi"] for k in y), 0)
    m["IPCut"] = f(r["ip_cut_scan"]["chosen"], 0)
    res = r["resolution_mumu"]
    m["DirResMed"] = f(res["tau_dir_err_mrad"][2], 1)
    m["DirResSixEight"] = f(res["tau_dir_err_mrad"][3], 1)
    m["LnVLo"] = f(res["ln_vreco_over_vtrue"][1], 2)
    m["LnVHi"] = f(res["ln_vreco_over_vtrue"][3], 2)
    m["LnVLoTwo"] = f(res["ln_vreco_over_vtrue"][0], 1)
    m["LnVHiTwo"] = f(res["ln_vreco_over_vtrue"][4], 1)
    m["LRatioLo"] = f(res["L_reco_over_true"][1], 2)
    m["LRatioHi"] = f(res["L_reco_over_true"][3], 2)
    words = {2: "Two", 5: "Five", 9: "Nine", 16: "Sixteen", 30: "Thirty", 50: "Fifty"}
    for row in r["migration_mumu"]:
        m[f"MigFrac{words[row['v']]}"] = (f(100 * row["frac_truly_below"], 0)
                                          if row["frac_truly_below"] is not None else "--")
    sp = r["spin_after_selection"]["mumu"]
    m["BRecoSel"] = f(sp["B_reco_selected"][0], 3)
    m["BTruthSel"] = f(sp["B_truth_selected"][0], 3)
    m["CnnReco"] = f(sp["C_reco_selected"][0][0], 2)
    m["CrrReco"] = f(sp["C_reco_selected"][1][1], 2)
    m["CkkReco"] = f(sp["C_reco_selected"][2][2], 2)
    t = next(x for x in tg if "mumu_A" in x["sample"])
    m["TruthB"] = f(t["B"][0], 3)
    m["TruthBErr"] = f(t["B"][1], 3)
    m["TruthTimelike"] = f(t["timelike_fraction"] * 1e4, 1)
    m["TruthTimelikeExp"] = f(t["timelike_expected"] * 1e4, 1)
    m["TruthCtau"] = f(t["ctau_um"][0], 1)
    m["ClosureDir"] = f(cl["tau_dir_err_median_mrad_clean"], 2)
    m["WhizKSPion"] = f(wz["pion_energy"]["p_value"], 2)
    m["WhizKSRecoil"] = f(wz["recoil_mass"]["p_value"], 2)
    lim = r["limits"]
    for scen, st in (("mumu", "MuMu"), ("ll", "LL"), ("visible", "Vis")):
        for alt, at in (("no_correlation", "NoCorr"), ("local_bound", "Local")):
            v = lim[scen][alt]["v95"]
            m[f"Reach{st}{at}"] = sig(v["p50"])
            m[f"Reach{st}{at}Lo"] = sig(v["p15.9"])
            m[f"Reach{st}{at}Hi"] = sig(v["p84.1"])
    bad = [k for k in m if not k.isalpha()]
    assert not bad, f"LaTeX macro names must be letters only: {bad}"
    with open("paper/v2/numbers.tex", "w") as fh:
        fh.write("% Generated by v2/make_numbers.py from results/*.json. Do not edit.\n")
        for k, v in m.items():
            fh.write(f"\\newcommand{{\\num{k}}}{{{v}}}\n")
    print(f"wrote {len(m)} macros to paper/v2/numbers.tex")


if __name__ == "__main__":
    main()
